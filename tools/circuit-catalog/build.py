def get(url, raw=False):
    CACHE.mkdir(exist_ok=True)
    f = CACHE / (hashlib.sha1(url.encode()).hexdigest() + (".txt" if raw else ".json"))
    if f.exists():
        return f.read_text() if raw else json.loads(f.read_text())
    for attempt in range(5):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
                body = r.read().decode()
            f.write_text(body)
            time.sleep(1.0)
            return body if raw else json.loads(body)
        except urllib.error.HTTPError as e:
            if e.code in (429, 500, 502, 503) and attempt < 4:
                time.sleep(4 * (attempt + 1))
                continue
            raise
    raise RuntimeError(f"gave up: {url}")


def wiki_raw(title):
    return get(f"https://en.wikipedia.org/w/index.php?title={urllib.parse.quote(title)}&action=raw", raw=True)


def link_text(s):
    m = re.search(r"\[\[([^\]|]+)(?:\|([^\]]+))?\]\]", s)
    return (m.group(2) or m.group(1)).strip() if m else re.sub(r"\{\{[^}]*\}\}", "", s).strip()


def link_target(s):
    m = re.search(r"\[\[([^\]|]+)", s)
    return m.group(1).strip() if m else None


def parse_table(text):
    tab = text[text.index('{| class="wikitable sortable"'):]
    tab = tab[: tab.index("\n|}")]
    out = {}
    for row in tab.split("\n|-")[1:]:
        cells = [c[1:] for c in row.strip().split("\n") if c.startswith("|")]
        if len(cells) < 11:
            continue
        name = re.sub(r"'''|\*|\{\{Dagger\}\}", "", link_text(cells[0])).strip()
        km = re.search(r"[Cc]onvert\|([\d.]+)\|km", cells[6])
        turns = re.sub(r"[^\d]", "", re.sub(r"\{\{efn[^}]*\}\}", "", cells[7]))
        out[name] = {
            "article": link_target(cells[0]),
            "type": cells[2].strip(),
            "direction": cells[3].strip(),
            "locality": link_text(cells[4]),
            "country": link_text(cells[5]),
            "lengthKm": float(km.group(1)) if km else None,
            "turns": int(turns) if turns else None,
        }
    return out


def infobox_fields(text):
    """Infobox parameters `|key = value` (values cut at the next parameter or the end of the infobox)."""
    fields = {}
    for m in re.finditer(r"^\s*\|\s*([a-z_0-9]+)\s*=\s*(.*)$", text[:20000], re.M):
        fields.setdefault(m.group(1), m.group(2).strip())
    return fields


def clean(v):
    v = re.sub(r"<!--.*?(-->|$)", "", v)
    v = re.sub(r"<ref[^>]*?/>|<ref.*?</ref>", "", v)
    v = re.sub(r"\{\{flagicon\|[^}]*\}\}", "", v, flags=re.I)
    return link_text(v).strip() if "[[" in v else re.sub(r"\{\{[^}]*\}\}", "", v).strip()


def lap_record(fields, gp_length_km):
    """The F1 race lap record of the layout matching the Grand Prix length (suffixes "", 2, 3, ...), else None."""
    for suffix in [""] + [str(i) for i in range(2, 12)]:
        length = fields.get(f"length{suffix}_km") or (fields.get("length_km") if suffix == "" else None)
        cls = fields.get(f"record_class{suffix}", "")
        t = fields.get(f"record_time{suffix}")
        if not (length and t):
            continue
        try:
            length_km = float(re.match(r"[\d.]+", clean(length)).group(0))
        except (AttributeError, ValueError):
            continue
        if gp_length_km is None or abs(length_km - gp_length_km) > 0.01:
            continue
        # An F1 record: class says so, or (class missing) the record year links to a Grand Prix article.
        if not (re.search(r"Formula One|\bF1\b", cls) or (not cls and "Grand Prix" in fields.get(f"record_year{suffix}", ""))):
            return None
        m = re.match(r"\d:\d{2}\.\d{3}", clean(t))
        if not m:
            return None
        time_s = m.group(0)
        return {"time": time_s, "driver": clean(fields.get(f"record_driver{suffix}", "")) or None, "car": clean(fields.get(f"record_car{suffix}", "")) or None,
                "year": int(re.sub(r"[^\d]", "", clean(fields.get(f"record_year{suffix}", ""))) or 0) or None, "layoutLengthKm": length_km}
    return None


def main():
    table = parse_table(wiki_raw(LIST_TITLE))
    seasons = {}
    for year in (2023, 2024, 2025, 2026):
        for m in get(f"https://api.openf1.org/v1/meetings?year={year}"):
            if "Testing" in m.get("meeting_name", ""):
                continue
            s = m.get("circuit_short_name")
            seasons.setdefault(s, {"key": m.get("circuit_key"), "meetings": []})["meetings"].append(
                {"year": year, "name": m.get("meeting_name"), "officialName": m.get("meeting_official_name"), "date": (m.get("date_start") or "")[:10]})
    results = {}
    for year in (2024, 2025, 2026):
        p = DATA.parent / "results" / f"{year}.json"
        if p.exists():
            d = json.loads(p.read_text())
            results[year] = ({e["circuitShortName"] for e in d["events"]}, {s["name"] for s in d.get("skipped", [])})

    circuits, problems = [], []
    for short, (slug, table_name) in LIBRARY.items():
        row = table.get(table_name)
        if not row:
            problems.append(f"{short}: no row '{table_name}' in the Wikipedia table")
            continue
        article = row["article"] or table_name
        fields = infobox_fields(wiki_raw(article))
        meet = seasons.get(short)
        if not meet:
            problems.append(f"{short}: not found in OpenF1 meetings")
            continue
        m26 = [m for m in meet["meetings"] if m["year"] == 2026]
        held_2026 = short in results.get(2026, (set(), set()))[0]
        # 2026: held (a classification exists), upcoming (date still ahead), or not held (date passed, nothing published).
        season2026 = None if not m26 else "held" if held_2026 else "upcoming" if m26[0]["date"] > ACCESSED else "not-held"
        geom = DATA / f"{slug}.geometry.json"
        g = json.loads(geom.read_text()) if geom.exists() else None
        circuits.append({
            "id": slug,
            "name": table_name,
            "shortName": SHORT_NAMES[slug],
            "openf1": {"circuitKey": meet["key"], "shortName": short},
            "locality": row["locality"],
            "country": row["country"],
            "countryCode": COUNTRY_CODES.get(row["country"]),
            "type": {"Street circuit": "street", "Race circuit": "permanent", "Road circuit": "road"}.get(row["type"], None),
            "direction": "clockwise" if row["direction"] == "Clockwise" else "anticlockwise" if row["direction"] == "Anti-clockwise" else "figure-of-eight" if "figure of eight" in row["direction"] else None,
            "lengthKm": row["lengthKm"],
            "turns": row["turns"],
            "lapRecord": lap_record(fields, row["lengthKm"]),
            "grandsPrix": [m for m in meet["meetings"] if m["year"] <= 2026],
            "calendar": "current" if m26 else "previous",
            "season2026": season2026,
            "wikipedia": f"https://en.wikipedia.org/wiki/{urllib.parse.quote(article.replace(' ', '_'))}",
            "geometry": None if not g else {"file": geom.name, "sessionKeys": g["derivation"]["sessionKeys"],
                                            "scale": g["derivation"].get("scale", {}).get("status"), "verdict": g["derivation"].get("spikeVerdict")},
        })
    out = {
        "schema": "apex-f1/circuit-catalog@1",
        "generatedOn": ACCESSED,
        "scope": "Every circuit with a Formula One Grand Prix in the OpenF1 era (2023 onwards), so every entry has car-position data for its layout. Earlier circuits have no such source and are not included.",
        "sources": [
            {"name": "Wikipedia: List of Formula One circuits", "url": f"https://en.wikipedia.org/wiki/{LIST_TITLE}", "accessed": ACCESSED,
             "fields": ["name", "type", "direction", "locality", "country", "lengthKm", "turns"], "note": "Table states it is accurate as of the 2026 Singapore Grand Prix; lengths and turns are for the last configuration used in Formula One."},
            {"name": "Wikipedia circuit articles (infobox)", "url": "https://en.wikipedia.org", "accessed": ACCESSED, "fields": ["lapRecord"],
             "note": "Race lap record of the layout matching the Grand Prix length, Formula One class only; null otherwise."},
            {"name": "OpenF1 /meetings", "url": "https://api.openf1.org/v1/meetings", "accessed": ACCESSED, "fields": ["openf1", "grandsPrix", "calendar"]},
        ],
        "circuits": sorted(circuits, key=lambda c: c["name"]),
    }
    (DATA / "catalog.json").write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")
    print(f"wrote {len(circuits)} circuits; {sum(1 for c in circuits if c['geometry'])} with geometry; {sum(1 for c in circuits if c['lapRecord'])} lap records")
    for p in problems:
        print("PROBLEM", p, file=sys.stderr)


if __name__ == "__main__":
    main()
