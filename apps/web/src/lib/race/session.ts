export type Freshness = "waiting" | "fresh" | "delayed" | "stale" | "paused" | "finished" | "disconnected";

/**
 * How current the view is, from the wall-clock age of the last snapshot. Playback that is paused or finished is reported as such rather
 * than as stale; a failed source is "disconnected".
 */
export function freshness(o: { snapshot: RaceSnapshot | null; receivedAt: number | null; now: number; playing: boolean; sourceStatus: SourceStatus }): { state: Freshness; ageMs: number | null } {
  if (o.sourceStatus === "error") return { state: "disconnected", ageMs: null };
  if (!o.snapshot || o.receivedAt == null) return { state: "waiting", ageMs: null };
  const ageMs = Math.max(0, o.now - o.receivedAt);
  if (o.snapshot.session.status === "finished") return { state: "finished", ageMs };
  if (o.snapshot.mode !== "LIVE" && !o.playing) return { state: "paused", ageMs };
  return { state: ageMs < 2000 ? "fresh" : ageMs < 6000 ? "delayed" : "stale", ageMs };
}

/** Selection is shared by the circuit and the leaderboard: choosing the selected driver again clears it. */
export const toggleSelection = (current: string | null, id: string): string | null => (current === id ? null : id);

/** Keyboard stepping through the race order (ArrowUp/ArrowDown in the leaderboard). */
export function stepSelection(order: readonly string[], current: string | null, dir: 1 | -1): string | null {
  if (order.length === 0) return null;
  const i = current ? order.indexOf(current) : -1;
  if (i === -1) return dir === 1 ? order[0] : order[order.length - 1];
  return order[Math.max(0, Math.min(order.length - 1, i + dir))];
}

/**
 * Smooths markers between snapshots. Views render `delayMs` behind real time (one update interval) so there are normally two snapshots
 * to interpolate between; a new epoch (reset/seek) clears the history so cars jump instead of sweeping round the lap.
 */
export class SnapshotBuffer {
  private items: Array<{ s: RaceSnapshot; at: number }> = [];
  constructor(private readonly delayMs: number) {}

  push(s: RaceSnapshot, at: number) {
    const last = this.items[this.items.length - 1];
    if (last && last.s.epoch !== s.epoch) this.items = [];
    this.items.push({ s, at });
    if (this.items.length > 4) this.items.shift();
  }

  clear() {
    this.items = [];
  }

  /** Interpolated progress per driver at wall-clock `now`, written into `out` (id -> progress). Missing positions are skipped. */
  sample(now: number, out: Map<string, number>) {
    out.clear();
    const n = this.items.length;
    if (n === 0) return;
    const rt = now - this.delayMs;
    // Bracket the render time: a = last snapshot at or before it, b = first at or after it (clamped to the ends of the history).
    let a = this.items[0];
    let b = this.items[n - 1];
    for (const it of this.items) if (it.at <= rt) a = it;
    for (const it of this.items)
      if (it.at >= rt) {
        b = it;
        break;
      }
    if (rt <= this.items[0].at) b = a = this.items[0];
    const span = b.at - a.at;
    const t = span > 0 ? (rt - a.at) / span : 1;
    const from = new Map(a.s.drivers.map((d) => [d.id, d.progress]));
    for (const d of b.s.drivers) {
      if (d.progress == null) continue;
      const p0 = from.get(d.id);
      out.set(d.id, p0 == null ? d.progress : lerpProgress(p0, d.progress, t));
    }
  }
}
