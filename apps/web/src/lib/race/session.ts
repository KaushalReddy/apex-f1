import type { DriverState, RaceMode, RaceSnapshot, SourceStatus } from "./types";

/** Race order: by position when known; cars without a position follow, in a stable order (car number, then id). */
export function sortByRaceOrder(drivers: readonly DriverState[]): DriverState[] {
  return [...drivers].sort((a, b) => {
    if (a.position != null && b.position != null) return a.position - b.position;
    if (a.position != null) return -1;
    if (b.position != null) return 1;
    return (a.number ?? Infinity) - (b.number ?? Infinity) || a.id.localeCompare(b.id);
  });
}

/** Adjacent pairs running within `thresholdS` of each other on the same lap. */
export function battles(s: RaceSnapshot, thresholdS = 1.0): Array<[string, string]> {
  if (!s.ordered) return [];
  const out: Array<[string, string]> = [];
  for (let i = 1; i < s.drivers.length; i++) {
    const d = s.drivers[i];
    const ahead = s.drivers[i - 1];
    if (d.finished || ahead.finished || d.pit === "in-pit" || ahead.pit === "in-pit") continue;
    if (d.gapAheadS != null && d.gapAheadS <= thresholdS && (d.lapsDown ?? 0) === (ahead.lapsDown ?? 0)) out.push([ahead.id, d.id]);
  }
  return out;
}

/** Gap text: "Leader", "+1.234", "+1 lap", or "—" when the source does not supply one. */
export function formatGap(d: DriverState, kind: "leader" | "ahead"): string {
  if (d.position === 1) return kind === "leader" ? "Leader" : "—";
  if (kind === "leader" && (d.lapsDown ?? 0) >= 1) return `+${d.lapsDown} lap${d.lapsDown === 1 ? "" : "s"}`;
  const g = kind === "leader" ? d.gapToLeaderS : d.gapAheadS;
  return g == null ? "—" : `+${g.toFixed(3)}`;
}

export function formatLapTime(ms: number | null): string {
  if (ms == null) return "—";
  const m = Math.floor(ms / 60000);
  const s = (ms % 60000) / 1000;
  return `${m}:${s.toFixed(3).padStart(6, "0")}`;
}

